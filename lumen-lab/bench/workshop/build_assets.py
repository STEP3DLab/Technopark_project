def fixture():
    width,depth,height,bore,full_depth=80.,40.,60.,6.2,50.
    tip=bore/2/math.tan(math.radians(59))
    block=cq.Workplane('XY').box(width,depth,height,centered=(False,False,False)).val()
    holes=[]
    for x in (20.,40.,60.):
        holes.extend([cq.Solid.makeCylinder(bore/2,full_depth+.1,(x,20.,height-full_depth)),
                      cq.Solid.makeCone(0,bore/2,tip,(x,20.,height-full_depth-tip))])
    block=block.cut(*holes).clean()
    assert block.isValid() and len(block.Solids())==1
    analytic=width*depth*height-3*(math.pi*(bore/2)**2*full_depth+math.pi*(bore/2)**2*tip/3)
    assert abs(block.Volume()-analytic)<1e-6
    cq.exporters.export(block,str(HERE/'thermal-block.step'))
    bb=block.BoundingBox()
    report={'revision':'TB-1','material':'Aluminium, density assumption 2700 kg/m3','units':'mm',
      'valid_solid':block.isValid(),'solid_count':len(block.Solids()),'bbox_mm':[bb.xlen,bb.ylen,bb.zlen],
      'bore_diameter_mm':bore,'full_diameter_depth_mm':full_depth,'drill_point_angle_deg':118,
      'centres_xy_mm':[[20,20],[40,20],[60,20]],'minimum_bottom_wall_mm':height-full_depth-tip,
      'volume_mm3':block.Volume(),'analytical_volume_mm3':analytic,'mass_kg_assuming_density_2700':block.Volume()*2.7e-6,
      'physically_built':False,'thermal_uniformity_measured':False,'thermal_stability_measured':False,
      'step_sha256':hashlib.sha256((HERE/'thermal-block.step').read_bytes()).hexdigest()}
    (HERE/'thermal-block-validation.json').write_text(json.dumps(report,indent=2)+'\n')
    c=canvas.Canvas(str(HERE/'thermal-block.pdf'),pagesize=A4,invariant=1)
    c.setTitle('LM-04B / TB-1 / Passive aluminium comparison block')
    def text(x,y,s,size=10,bold=False):c.setFont('Bold' if bold else 'Text',size);c.drawString(x*mm,y*mm,s)
    def line(x1,y1,x2,y2):c.line(x1*mm,y1*mm,x2*mm,y2*mm)
    def dim(x1,y1,x2,y2,label):
        line(x1,y1,x2,y2)
        for x,y in [(x1,y1),(x2,y2)]:line(x-1.3,y-1.3,x+1.3,y+1.3)
        text((x1+x2)/2-4,(y1+y2)/2+2,label,9)
    text(18,278,'LM-04B / TB-1',11,True);text(18,266,'Блок сопоставления термометров',17,True)
    text(18,256,'Пассивная деталь из алюминия. Размеры в мм. Масштаб видов 1:1.',9)
    # Top view, three separate bores at real size.
    ox,oy=42,194;c.setLineWidth(.7);c.rect(ox*mm,oy*mm,80*mm,40*mm)
    for x,label in [(20,'T1'),(40,'REF'),(60,'T2')]:
        c.circle((ox+x)*mm,(oy+20)*mm,3.1*mm)
        c.setDash(3,2);line(ox+x-5,oy+20,ox+x+5,oy+20);line(ox+x,oy+15,ox+x,oy+25);c.setDash()
        text(ox+x-3,oy+8,label,8)
    dim(ox,oy+46,ox+80,oy+46,'80');dim(ox+87,oy,ox+87,oy+40,'40')
    dim(ox,oy-8,ox+20,oy-8,'20');dim(ox+20,oy-8,ox+40,oy-8,'20');dim(ox+40,oy-8,ox+60,oy-8,'20')
    text(139,225,'3 отв. Ø6,2 +0,2',9);text(139,219,'Глубина полного',9);text(139,213,'диаметра 50 ±0,5',9)
